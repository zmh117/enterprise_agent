import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const runtimeRoot = resolve(scriptDir, "..");
const repositoryRoot = resolve(runtimeRoot, "..");
const v13 = process.argv.includes("--v1.3");
const protocolVersion = v13 ? "1.3" : "1.2";
const versionSuffix = v13 ? "v1_3" : "v1_2";
const requestDefinition = v13 ? "AgentExecutionRequestV13" : "AgentExecutionRequestV12";
const schemaPath = resolve(
  repositoryRoot,
  `contracts/agent-runtime/v${protocolVersion}/protocol.schema.json`
);
const schemaText = await readFile(schemaPath, "utf8");
const schema = JSON.parse(schemaText);
const schemaDigest = createHash("sha256").update(schemaText).digest("hex");
const selectedDefinitions = [
  "Identifier",
  "Sha256Digest",
  "RuntimeKind",
  "SafeMessage",
  "JsonSummary",
  "ExecutionLimits",
  "Prompt",
  "ModelConnectionBinding",
  "ModelProbeRequest",
  "ModelProbeCredentialEnvelope",
  "DraftModelProbeRequest",
  "ModelProbeFailure",
  "ModelProbeResponse",
  "McpToolBinding",
  "McpServerBinding",
  ...(v13
    ? [
        "FileFormatPolicyVersion",
        "TextFormatCode",
        "FileAction",
        "JobFileManifestItem",
        "JobFileManifest",
        "FileContext"
      ]
    : []),
  requestDefinition,
  "RuntimeGrantClaims",
  "Usage",
  "McpConnectionStatus",
  "RuntimeInitialization",
  "ModelCall",
  "ApiRetry",
  "ModelUsageEntry",
  "ExecutionAccounting",
  "RuntimeProvenance",
  "RuntimeFailure",
  "ToolEvent",
  "TerminalResult",
  "CancelRequest",
  "RuntimeEvent"
];

function referencedName(ref) {
  return ref.split("/").at(-1);
}

function tsType(value) {
  if (value.$ref) return referencedName(value.$ref);
  if (Object.hasOwn(value, "const")) return JSON.stringify(value.const);
  if (value.enum) return value.enum.map((item) => JSON.stringify(item)).join(" | ");
  if (value.oneOf) return value.oneOf.map(tsType).join(" | ");
  if (Array.isArray(value.type)) return value.type.map((item) => tsType({ type: item })).join(" | ");
  if (value.type === "array") return `Array<${tsType(value.items ?? {})}>`;
  if (value.type === "object") {
    const required = new Set(value.required ?? []);
    const properties = Object.entries(value.properties ?? {}).map(
      ([name, property]) => `${JSON.stringify(name)}${required.has(name) ? "" : "?"}: ${tsType(property)};`
    );
    if (value.additionalProperties && typeof value.additionalProperties === "object") {
      return `Record<string, ${tsType(value.additionalProperties)}>`;
    }
    if (properties.length === 0) return "Record<string, unknown>";
    return `{ ${properties.join(" ")} }`;
  }
  if (value.type === "string") return "string";
  if (value.type === "number" || value.type === "integer") return "number";
  if (value.type === "boolean") return "boolean";
  if (value.type === "null") return "null";
  return "unknown";
}

function pyType(value) {
  if (value.$ref) return referencedName(value.$ref);
  if (Object.hasOwn(value, "const")) return `Literal[${pyLiteral(value.const)}]`;
  if (value.enum) return `Literal[${value.enum.map(pyLiteral).join(", ")}]`;
  if (value.oneOf) return value.oneOf.map(pyType).join(" | ");
  if (Array.isArray(value.type)) return value.type.map((item) => pyType({ type: item })).join(" | ");
  if (value.type === "array") return `list[${pyType(value.items ?? {})}]`;
  if (value.type === "object") {
    if (value.additionalProperties && typeof value.additionalProperties === "object") {
      return `dict[str, ${pyType(value.additionalProperties)}]`;
    }
    return "dict[str, object]";
  }
  if (value.type === "string") return "str";
  if (value.type === "number") return "float";
  if (value.type === "integer") return "int";
  if (value.type === "boolean") return "bool";
  if (value.type === "null") return "None";
  return "object";
}

function pyLiteral(value) {
  if (value === null) return "None";
  if (value === true) return "True";
  if (value === false) return "False";
  return JSON.stringify(value);
}

const tsDefinitions = selectedDefinitions
  .map((name) => `export type ${name} = ${tsType(schema.$defs[name])};`)
  .join("\n\n");
const tsOutput = `// Generated by scripts/generate-contracts-v1_2.mjs. Do not edit.\n\nexport const PROTOCOL_VERSION = "${protocolVersion}" as const;\nexport const CONTRACT_SCHEMA_SHA256 = "${schemaDigest}" as const;\n\n${tsDefinitions}\n`;

const pyClasses = selectedDefinitions
  .filter((name) => schema.$defs[name]?.type === "object")
  .map((name) => {
    const definition = schema.$defs[name];
    const required = new Set(definition.required ?? []);
    const properties = Object.entries(definition.properties ?? {});
    const lines = properties.map(([field, value]) => {
      const annotation = pyType(value);
      return `    ${field}: ${required.has(field) ? annotation : `NotRequired[${annotation}]`}`;
    });
    return `class ${name}(TypedDict):\n${lines.length ? lines.join("\n") : "    pass"}`;
  })
  .join("\n\n\n");
const pyAliases = selectedDefinitions
  .filter((name) => schema.$defs[name]?.type !== "object")
  .map((name) => `${name} = ${pyType(schema.$defs[name])}`)
  .join("\n");
const pyOutput = `# Generated by agent-runtime/scripts/generate-contracts-v1_2.mjs. Do not edit.\nfrom __future__ import annotations\n\nimport json\nfrom pathlib import Path\nfrom typing import Literal, NotRequired, TypedDict\n\nfrom jsonschema import Draft202012Validator\n\nPROTOCOL_VERSION = "${protocolVersion}"\nCONTRACT_SCHEMA_SHA256 = "${schemaDigest}"\nCONTRACT_SCHEMA_PATH = (\n    Path(__file__).resolve().parents[5]\n    / "contracts"\n    / "agent-runtime"\n    / "v${protocolVersion}"\n    / "protocol.schema.json"\n)\n\n${pyAliases}\n\n${pyClasses}\n\n\ndef validate_contract(definition_name: str, payload: object) -> None:\n    schema = json.loads(CONTRACT_SCHEMA_PATH.read_text(encoding="utf-8"))\n    definition = schema.get("$defs", {}).get(definition_name)\n    if definition is None:\n        raise ValueError(f"unknown runtime contract: {definition_name}")\n    validator = Draft202012Validator(\n        {"$ref": f"#/$defs/{definition_name}", "$defs": schema["$defs"]}\n    )\n    errors = sorted(validator.iter_errors(payload), key=lambda item: list(item.path))\n    if errors:\n        detail = "; ".join(error.message for error in errors[:8])\n        raise ValueError(f"invalid {definition_name}: {detail}")\n`;

const validatorOutput = `// Generated by scripts/generate-contracts-v1_2.mjs. Do not edit.
import { Ajv2020 } from "ajv/dist/2020.js";
import type { ErrorObject, ValidateFunction } from "ajv";
import * as addFormatsModule from "ajv-formats";

import protocolSchema from "../../contracts/v${protocolVersion}/protocol.schema.json" with { type: "json" };

const addFormats = addFormatsModule.default.default;
const ajv = new Ajv2020({ allErrors: true, strict: true, allowUnionTypes: true });
addFormats(ajv);
ajv.addSchema(protocolSchema);

export type ContractName = ${selectedDefinitions.map((name) => JSON.stringify(name)).join(" | ")};

export class ContractValidationError extends Error {
  constructor(
    readonly contractName: ContractName,
    readonly errors: ErrorObject[]
  ) {
    super(\`invalid \${contractName}: \${ajv.errorsText(errors, { separator: "; " })}\`);
    this.name = "ContractValidationError";
  }
}

function contractValidator(name: ContractName): ValidateFunction {
  const validator = ajv.getSchema(\`\${protocolSchema.$id}#/$defs/\${name}\`);
  if (!validator) throw new Error(\`missing contract definition: \${name}\`);
  return validator;
}

export function assertContract(name: ContractName, payload: unknown): void {
  const validator = contractValidator(name);
  if (!validator(payload)) {
    throw new ContractValidationError(name, validator.errors ?? []);
  }
}
`;

const outputs = [
  [resolve(runtimeRoot, `src/generated/contracts-${versionSuffix}.ts`), tsOutput],
  [resolve(runtimeRoot, `src/generated/validators-${versionSuffix}.ts`), validatorOutput],
  [
    resolve(
      repositoryRoot,
      `backend/app/modules/agent/infrastructure/generated_runtime_contracts_${versionSuffix}.py`
    ),
    pyOutput
  ]
];

const checkOnly = process.argv.includes("--check");
let changed = false;
for (const [path, content] of outputs) {
  let current = "";
  try {
    current = await readFile(path, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (current === content) continue;
  changed = true;
  if (!checkOnly) {
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, content, "utf8");
  }
}

if (checkOnly && changed) {
  throw new Error(`generated runtime ${protocolVersion} contracts are out of date`);
}
